import { describe, expect, it } from 'vitest'
import { typo } from '@/lib/typo'

const NB = '\u00a0'

describe('E1: typo', () => {
  it('склеивает короткое слово со следующим', () => {
    expect(typo('Мойка в боксе')).toBe(`Мойка в${NB}боксе`)
  })

  it('склеивает число со следующим словом', () => {
    expect(typo('Запись на 60 дней')).toBe(`Запись на${NB}60${NB}дней`)
    expect(typo('Керамика в 3 слоя')).toBe(`Керамика в${NB}3${NB}слоя`)
  })

  it('склеивает число со знаком валюты', () => {
    expect(typo('от 1500 ₽')).toBe(`от${NB}1500${NB}₽`)
  })

  it('ставит неразрывный пробел перед длинным тире, после тире пробел остаётся обычным', () => {
    expect(typo('Чисто — и всё')).toBe(`Чисто${NB}— и${NB}всё`)
  })

  it('обрабатывает цепочку коротких слов, в том числе с заглавной буквы', () => {
    const result = typo('А я и не знал')
    expect(result).toBe(`А${NB}я${NB}и${NB}не${NB}знал`)
    expect(result).not.toContain(' ')
  })

  it('не трогает слова длиннее двух букв', () => {
    expect(typo('для всех машин')).toBe('для всех машин')
  })

  it('строка без коротких слов и чисел не меняется', () => {
    expect(typo('Бережная мойка кузова')).toBe('Бережная мойка кузова')
    expect(typo('Химчистка салона')).toBe('Химчистка салона')
  })

  it('меняет только пробелы, остальной текст остаётся прежним', () => {
    const samples = ['Мойка в боксе', 'Запись на 60 дней', 'Чисто — и всё', 'А я и не знал', 'Чистка кондиционера, если он есть']
    for (const s of samples) {
      expect(typo(s).replace(/\u00a0/g, ' ')).toBe(s)
    }
  })

  it('идемпотентна', () => {
    for (const s of ['Мойка в боксе', 'Запись на 60 дней', 'Чисто — и всё']) {
      expect(typo(typo(s))).toBe(typo(s))
    }
  })

  it('пустая строка остаётся пустой', () => {
    expect(typo('')).toBe('')
  })
})
