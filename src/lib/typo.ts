const NB = ' '

/**
 * Неразрывные пробелы по правилам русской вёрстки: после слов из 1–2 букв,
 * перед длинным тире, между числом и следующим словом или знаком, внутри «1 500».
 * Меняет только обычные пробелы, поэтому повторный вызов ничего не меняет.
 */
export function typo(text: string): string {
  return text
    .replace(/(?<![\p{L}\p{N}-])(\p{L}{1,2}) /gu, `$1${NB}`)
    .replace(/ (?=—)/g, NB)
    .replace(/(\d) (?=[\p{L}₽%°]|\d{3}(?!\d))/gu, `$1${NB}`)
}
